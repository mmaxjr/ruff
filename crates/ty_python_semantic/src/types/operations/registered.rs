//! The source computations allowed to create independent semantic operation owners.
//!
//! Adding a query here requires checking that its result depends only on its explicit inputs,
//! rather than on recursion guards held by a caller. Implementations live beside their source data.

macro_rules! queries {
    ($($query:ident),* $(,)?) => {
        $(pub(crate) struct $query;
        impl super::sealed::SourceQuery for $query {})*
    };
}

